import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { ignoreRules, isIgnored, repositoryFiles } from '../scripts/repository-files.js';

/**
 * Paths are joined from their segments so that this file cites no path the
 * repository does not hold: the examples name files in a folder built for each
 * test and thrown away after it.
 */
const at = (...segments: string[]): string => segments.join('/');

const folders: string[] = [];

function folderWith(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'repository-files-'));
  folders.push(root);
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

afterEach(() => {
  for (const root of folders.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

describe('reading an ignore file', () => {
  // A blank line or a comment in .gitignore names no file. If either were read as a rule, a file
  // that ships could be left out of the walk without anyone noticing.
  it('holds no rule for a blank line or a comment', () => {
    expect(ignoreRules('\n# generated by the build\n\n')).toEqual([]);
  });

  // A negation puts back a file an earlier rule left out. This reader does not follow negations, so
  // it refuses one and says which line, rather than leave out a file git would keep.
  it('refuses a negation, naming the line, rather than guessing what it re-includes', () => {
    expect(() => ignoreRules('dist/\n!keep.js\n')).toThrow(/line 2, "!keep.js", is a negation/);
  });

  // A double star crosses folders, which this reader does not follow. Read as two single stars it
  // would quietly cover fewer files than git does, so it is refused instead.
  it('refuses a double star', () => {
    expect(() => ignoreRules('docs/**/draft\n')).toThrow(/is a double star/);
  });

  // A question mark, a character class or an escape means something to git that this reader would
  // get wrong, so each is refused with the line it is on.
  it('refuses a question mark, a character class and an escape', () => {
    expect(() => ignoreRules('file?\n')).toThrow(/wildcard character or an escape/);
    expect(() => ignoreRules('[ab].log\n')).toThrow(/wildcard character or an escape/);
    expect(() => ignoreRules('\\#name\n')).toThrow(/wildcard character or an escape/);
  });

  // Git reads a space at the start of a line as part of the name. Trimming it would make " dist/"
  // cover a folder git keeps, so such a line is refused.
  it('refuses a rule that starts with a space, which git reads as part of the name', () => {
    expect(() => ignoreRules(' dist/\n')).toThrow(/starting with a space/);
  });

  // A line saved with a carriage return or trailing spaces still means the rule before them. Kept
  // as written, the rule would name nothing on disk and cover nothing.
  it('reads a line ending in a carriage return or spaces as the rule before them', () => {
    const [rule] = ignoreRules('dist/  \r\n');
    expect(rule?.source).toBe('dist/');
    expect(rule?.directoryOnly).toBe(true);
  });
});

describe('what a rule covers', () => {
  const rules = ignoreRules('node_modules/\ncontracts/managed/\n*.tsbuildinfo\n.DS_Store\n');

  // A rule with no slash in it names a file or folder at any depth, so a .DS_Store deep in the tree
  // is left out just like one at the top.
  it('covers a bare name at any depth', () => {
    expect(isIgnored(rules, '.DS_Store', false)).toBe(true);
    expect(isIgnored(rules, at('src', '.DS_Store'), false)).toBe(true);
  });

  // A rule with a slash in it is a path from the top of the repository. A folder of the same name
  // deeper down is a different folder, and it is kept.
  it('covers a path with a slash only from the top', () => {
    expect(isIgnored(rules, at('contracts', 'managed'), true)).toBe(true);
    expect(isIgnored(rules, at('other', 'contracts', 'managed'), true)).toBe(false);
  });

  // When a rule names a folder, every file inside it is left out too, however deep.
  it('covers every file inside a directory it names', () => {
    expect(isIgnored(rules, at('contracts', 'managed', 'contract', 'index.js'), false)).toBe(true);
    expect(isIgnored(rules, at('node_modules', 'a', 'package.json'), false)).toBe(true);
  });

  // A trailing slash means the rule names folders only. A plain file that happens to share the name
  // is not covered, and it ships.
  it('leaves a file alone that only shares its name with a directory rule', () => {
    expect(isIgnored(rules, 'node_modules', false)).toBe(false);
  });

  // A star matches within one segment of a path and never across a slash, so a rule for one folder
  // does not reach into the folders below it.
  it('keeps a star inside one segment', () => {
    expect(isIgnored(rules, at('build', 'a.tsbuildinfo'), false)).toBe(true);
    const anchored = ignoreRules('src/*.ts\n');
    expect(isIgnored(anchored, at('src', 'a.ts'), false)).toBe(true);
    expect(isIgnored(anchored, at('src', 'deeper', 'a.ts'), false)).toBe(false);
  });

  // A leading slash ties a rule to the top of the repository: it covers the folder there and not
  // one of the same name deeper down.
  it('reads a leading slash as the top of the repository', () => {
    const top = ignoreRules('/build\n');
    expect(isIgnored(top, 'build', true)).toBe(true);
    expect(isIgnored(top, at('src', 'build'), true)).toBe(false);
  });

  // A rule covers exactly the name it is written as. Dots, the end of the name and characters such
  // as + ^ $ ( ) | are taken literally, because a rule that covered more would drop files from
  // every check.
  it('covers the name it is written as and nothing more', () => {
    expect(isIgnored(rules, 'aDS_Store', false)).toBe(false);
    expect(isIgnored(rules, '.DS_Store.bak', false)).toBe(false);
    expect(isIgnored(ignoreRules('a+b\n'), 'aab', false)).toBe(false);
    expect(isIgnored(ignoreRules('a(b)|c\n'), 'c', false)).toBe(false);
    expect(isIgnored(ignoreRules('a(b)|c\n'), 'a(b)|c', false)).toBe(true);
    expect(isIgnored(ignoreRules('a^b$c\n'), 'a^b$c', false)).toBe(true);
  });

  // A file no rule names is kept. This is the ordinary case, and every source file depends on it.
  it('keeps a file no rule names', () => {
    expect(isIgnored(rules, at('src', 'index.ts'), false)).toBe(false);
  });
});

describe('the files a folder holds', () => {
  // The walk lists every file the ignore file does not name, in sorted order. It leaves out every
  // .git folder, at any depth, and it still goes into folders whose names start with a dot, such as
  // .github.
  it('is every file the ignore file does not name, outside git, in order', () => {
    const root = folderWith({
      '.gitignore': 'dist/\n*.log\n',
      'README.md': '',
      [at('.github', 'workflows', 'check.yml')]: '',
      [at('src', 'index.ts')]: '',
      [at('src', 'a.ts')]: '',
      [at('dist', 'index.js')]: '',
      'run.log': '',
      [at('.git', 'config')]: '',
      [at('vendor', 'copy', '.git', 'HEAD')]: '',
      [at('vendor', 'copy', 'notes')]: '',
    });
    expect(repositoryFiles(root)).toEqual([
      at('.github', 'workflows', 'check.yml'),
      '.gitignore',
      'README.md',
      at('src', 'a.ts'),
      at('src', 'index.ts'),
      at('vendor', 'copy', 'notes'),
    ]);
  });

  // A folder with no ignore file is not an error: every file in it is listed.
  it('is every file when there is no ignore file', () => {
    const root = folderWith({ [at('src', 'index.ts')]: '' });
    expect(repositoryFiles(root)).toEqual([at('src', 'index.ts')]);
  });

  // A symbolic link points at something outside the repository's own files, so the walk refuses it
  // rather than read the target as if it were part of the repository.
  it('refuses a symbolic link, because what it points at is not here', () => {
    const root = folderWith({ 'README.md': '' });
    symlinkSync(join(root, 'README.md'), join(root, 'pointer.md'));
    expect(() => repositoryFiles(root)).toThrow(/pointer.md is a symbolic link/);
  });

  // Only the top ignore file is read. A second one deeper in the tree would have rules this walk
  // never applies, so the walk refuses it rather than list files git would leave out.
  it('refuses a second ignore file, whose rules it would not read', () => {
    const root = folderWith({
      [at('src', '.gitignore')]: 'secret.ts\n',
      [at('src', 'secret.ts')]: '',
    });
    expect(() => repositoryFiles(root)).toThrow(/is a second ignore file/);
  });

  // Whatever the rules leave out is never looked at, so a link or an ignore file inside an
  // installed package or a named path cannot stop the walk.
  it('asks nothing of what the rules name', () => {
    const root = folderWith({
      '.gitignore': 'node_modules/\nlinked\nsrc/.gitignore\n',
      [at('node_modules', 'a', 'index.js')]: '',
      [at('src', '.gitignore')]: 'x\n',
      [at('src', 'a.ts')]: '',
    });
    symlinkSync(join(root, 'node_modules', 'a', 'index.js'), join(root, 'linked'));
    expect(repositoryFiles(root)).toEqual(['.gitignore', at('src', 'a.ts')]);
  });
});

describe('this repository', () => {
  const root = resolve(import.meta.dirname, '..');
  const files = (): string[] => repositoryFiles(root);

  // The walk over this repository finds its own sources, its checks, this test and the workflows,
  // so the checks that read the walk read them too.
  it('holds its sources, its checks and this test', () => {
    expect(files()).toContain('package.json');
    expect(files()).toContain(at('scripts', 'repository-files.ts'));
    expect(files()).toContain(at('test', 'repository-files.test.ts'));
    expect(files()).toContain(at('.github', 'workflows', 'ci.yml'));
  });

  // Nothing the repository's own ignore file names, such as installed packages or compiler output,
  // is in the walk.
  it('holds nothing its ignore file names', () => {
    const rules = ignoreRules(readFileSync(join(root, '.gitignore'), 'utf8'));
    expect(rules.length).toBeGreaterThan(0);
    expect(files().filter((path) => isIgnored(rules, path, false))).toEqual([]);
  });
});
